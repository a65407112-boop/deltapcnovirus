dofile('tests/roblox_mock.lua')
Mock.services.UserInputService.TouchEnabled=true
local start=assert(loadfile('client.lua'))()
local input=Mock.services.UserInputService
local failures={}
local ui
local function near(a,b) return math.abs(a-b)<.001 end
local function touch(x,y) return {UserInputType=Enum.UserInputType.Touch,Position=Vector2.new(x,y)} end
local function case(name,callback)
    Mock.geometry={};Mock.noneInset=nil;Mock.coreInset=nil
    workspace.CurrentCamera.ViewportSize=Vector2.new(1280,720)
    ui=start({keyed=false})
    ui.launcher.Position=UDim2.fromOffset(100,80)
    local ok,err=pcall(callback)
    ui.close();Mock.flush()
    if not ok then failures[#failures+1]=name..': '..tostring(err) end
end
case('reference icon',function()
    local l=ui.launcher;local outline=l:FindFirstChildOfClass('UIStroke')
    assert(outline and outline.Thickness==2,'Use a thin outline')
    assert(l.BackgroundColor3.B<.3 and outline.Color.B>.8,'Dark fill, blue border')
    assert(l.Size.X.Offset==48,'Match the smaller original medium icon')
    assert(l:FindFirstChild('Logo').Image:find('logo.png',1,true))
    assert(l.AutoButtonColor==false,'Dragging must not recolor the icon')
    ui.open();ui.nodes[42].Activated:Fire();ui.nodes[308].Activated:Fire();ui.nodes[327].Activated:Fire()
    assert(l.BackgroundColor3.B<.3 and outline.Color.R>.5,'Color setting changes the outline only')
end)
case('scaled and inset host',function()
    local l=ui.launcher;local size=l.Size.X.Offset
    Mock.geometry[l]={AbsolutePosition=Vector2.new(230,220),AbsoluteSize=Vector2.new(size*2,size*2)}
    Mock.geometry[ui.gui]={AbsolutePosition=Vector2.new(30,60),AbsoluteSize=Vector2.new(1600,1200)}
    local t=touch(260,252);l.InputBegan:Fire(t)
    t.Position=Vector2.new(300,282);input.InputChanged:Fire(t)
    assert(near(l.Position.X.Offset,120) and near(l.Position.Y.Offset,95),'Preserve grab offset in parent coordinates')
end)
case('single finger ownership',function()
    local l=ui.launcher;local first=touch(110,90);local second=touch(130,100)
    l.InputBegan:Fire(first);l.InputBegan:Fire(second)
    first.Position=Vector2.new(140,110);input.InputChanged:Fire(first)
    assert(near(l.Position.X.Offset,130) and near(l.Position.Y.Offset,100),'Second finger must not replace the active drag')
    second.Position=Vector2.new(900,900);input.InputChanged:Fire(second);input.InputEnded:Fire(second);l.Activated:Fire(second)
    assert(not ui.state.opened and near(l.Position.X.Offset,130),'Ignore unrelated touch movement/release')
end)
case('immediate movement',function()
    local t=touch(110,90);ui.launcher.InputBegan:Fire(t)
    t.Position=Vector2.new(112,91);input.InputChanged:Fire(t)
    assert(near(ui.launcher.Position.X.Offset,102) and near(ui.launcher.Position.Y.Offset,81),'Follow the finger before the click/drag threshold')
end)
case('late release activation',function()
    local t=touch(110,90);ui.launcher.InputBegan:Fire(t)
    t.Position=Vector2.new(150,120);input.InputChanged:Fire(t)
    t.Position=Vector2.new(110,90);input.InputChanged:Fire(t);input.InputEnded:Fire(t)
    Mock.flush();ui.launcher.Activated:Fire(t)
    assert(not ui.state.opened,'A delayed release must never turn a completed drag into a tap')
    local tap=touch(110,90);ui.launcher.InputBegan:Fire(tap);input.InputEnded:Fire(tap);ui.launcher.Activated:Fire(tap)
    assert(ui.state.opened,'The next real tap opens normally')
end)
case('safe areas and rotation',function()
    Mock.noneInset=Rect.new(-20,-48,780,552);Mock.coreInset=Rect.new(0,0,760,520)
    Mock.geometry[ui.gui]={AbsolutePosition=Vector2.new(-20,-48)}
    workspace.CurrentCamera.ViewportSize=Vector2.new(800,600)
    local t=touch(110,90);ui.launcher.InputBegan:Fire(t)
    t.Position=Vector2.new(-1000,-1000);input.InputChanged:Fire(t)
    assert(near(ui.launcher.Position.X.Offset,28) and near(ui.launcher.Position.Y.Offset,56),'Apply the safe-area origin exactly once')
    t.Position=Vector2.new(2000,2000);input.InputChanged:Fire(t)
    local size=ui.launcher.Size.X.Offset
    assert(near(ui.launcher.Position.X.Offset,780-size-8) and near(ui.launcher.Position.Y.Offset,568-size-8),'Respect right/bottom cutouts too')
    workspace.CurrentCamera.ViewportSize=Vector2.new(390,844)
    input.InputEnded:Fire(t);ui.launcher.Activated:Fire(t)
    assert(not ui.state.opened and ui.launcher.Position.X.Offset<=390-ui.launcher.Size.X.Offset-8)
end)
case('lost focus',function()
    local t=touch(110,90);ui.launcher.InputBegan:Fire(t);input.WindowFocusReleased:Fire()
    input.InputEnded:Fire(t);ui.launcher.Activated:Fire(t);assert(not ui.state.opened)
    local tap=touch(110,90);ui.launcher.InputBegan:Fire(tap);input.InputEnded:Fire(tap);ui.launcher.Activated:Fire(tap)
    assert(ui.state.opened)
end)
case('hold title for AUTO',function()
    ui.open();ui.nodes[34].Activated:Fire()
    local item=ui.state:saveScript('Mobile','return 1');ui.renderSaved()
    local row=ui.nodes[554]:FindFirstChild('Saved_'..item.id)
    local t=touch(140,160);row.Edit.InputBegan:Fire(t);Mock.flush()
    assert(item.autoExecute,'Long press must expose AUTO without a right mouse button')
    input.InputEnded:Fire(t)
    row=ui.nodes[554]:FindFirstChild('Saved_'..item.id);row.Edit.Activated:Fire(t)
    assert(ui.state.page=='Home','Long press must not also open the script editor')
end)
case('scroll cancels title hold',function()
    ui.open();ui.nodes[34].Activated:Fire()
    local item=ui.state:saveScript('Swipe','return 2');ui.renderSaved()
    local row=ui.nodes[554]:FindFirstChild('Saved_'..item.id)
    local t=touch(140,160);row.Edit.InputBegan:Fire(t)
    t.Position=Vector2.new(140,210);input.InputChanged:Fire(t);Mock.flush()
    input.InputEnded:Fire(t);row.Edit.Activated:Fire(t)
    assert(not item.autoExecute and ui.state.page=='Home','A list swipe is neither a long press nor an edit tap')
end)
case('mobile clipboard fallback',function()
    ui.open();local read=getclipboard;getclipboard=nil
    ui.nodes[405].Activated:Fire();getclipboard=read
    assert(ui.status.Text:find('hold',1,true) and not ui.status.Text:find('Ctrl',1,true),'Show touch paste instructions')
end)
assert(#failures==0,table.concat(failures,'\n'))
assert(Mock.liveConnections()==0)
print('Mobile: reference launcher, scaled/inset drag, touch ownership, release ordering, safe areas, rotation, hold/scroll and clipboard')
